"""从已提交的 OpenAPI 生成 M0 使用的 Kotlin DTO；--check 用于契约漂移门禁。"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "mobile/shared/src/commonMain/kotlin/app/clipo/shared/model/generated/ApiModels.kt"
ROOT_MODELS = (
    "VersionResponse",
    "LoginRequest",
    "RefreshRequest",
    "SessionResponse",
    "ErrorResponse",
    "NotePage",
    "NoteResponse",
)


def class_name(name: str) -> str:
    return name.replace("-", "")


def property_name(name: str) -> str:
    return re.sub(r"_([a-z])", lambda match: match[1].upper(), name)


def generate(schemas: dict[str, Any]) -> str:
    pending = set(ROOT_MODELS)
    emitted: dict[str, str] = {}

    def kotlin_type(schema: dict[str, Any]) -> str:
        if "$ref" in schema:
            name = schema["$ref"].rsplit("/", 1)[1]
            pending.add(name)
            return class_name(name)
        if "anyOf" in schema:
            non_null = [item for item in schema["anyOf"] if item.get("type") != "null"]
            if len(non_null) != 1:
                raise ValueError(f"未支持的联合类型: {schema}")
            result = kotlin_type(non_null[0])
            return result + ("?" if len(non_null) != len(schema["anyOf"]) else "")
        kind = schema.get("type")
        if kind == "array":
            return f"List<{kotlin_type(schema['items'])}>"
        if kind == "object":
            return "JsonObject"
        return {"string": "String", "integer": "Long", "number": "Double", "boolean": "Boolean"}[
            kind
        ]

    while pending:
        name = sorted(pending)[0]
        pending.remove(name)
        if name in emitted:
            continue
        schema = schemas[name]
        fields = []
        for key, prop in schema["properties"].items():
            kind = kotlin_type(prop)
            default = ""
            if key not in schema.get("required", []):
                if "default" in prop and prop["default"] is not None:
                    value = json.dumps(prop["default"], ensure_ascii=False).replace("$", "\\$")
                    default = f" = {value}"
                elif kind.startswith("List<"):
                    default = " = emptyList()"
                else:
                    kind = kind.rstrip("?") + "?"
                    default = " = null"
            fields.append(f'    @SerialName("{key}") val {property_name(key)}: {kind}{default},')
        emitted[name] = "@Serializable\ndata class " + class_name(name) + "(\n"
        emitted[name] += "\n".join(fields) + "\n)\n"
    uses_json = any("JsonObject" in source for source in emitted.values())
    return (
        "// SPDX-License-Identifier: AGPL-3.0-or-later\n"
        "// Generated by scripts/generate_mobile_api.py; DO NOT EDIT.\n"
        "package app.clipo.shared.model.generated\n\n"
        "import kotlinx.serialization.SerialName\n"
        "import kotlinx.serialization.Serializable\n"
        + ("import kotlinx.serialization.json.JsonObject\n" if uses_json else "")
        + "\n"
        + "\n".join(emitted[name] for name in sorted(emitted))
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    schemas = json.loads((ROOT / "frontend/openapi.json").read_text())["components"]["schemas"]
    generated = generate(schemas)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            raise SystemExit("移动端 DTO 已漂移，请运行 python3 scripts/generate_mobile_api.py")
        print("移动端 DTO 与 OpenAPI 一致")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(generated)


if __name__ == "__main__":
    main()
